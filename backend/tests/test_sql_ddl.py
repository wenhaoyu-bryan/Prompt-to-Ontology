import unittest

from assisted_build.sql_ddl import parse_ddl


class SqlDdlTests(unittest.TestCase):
    def test_extracts_columns_and_requiredness(self):
        tables = parse_ddl("""
            -- source schema
            CREATE TABLE IF NOT EXISTS Sales."Supply Order" (
                Order_ID BIGSERIAL CONSTRAINT order_key PRIMARY KEY,
                amount NUMERIC(12, 2) NOT NULL CHECK (amount >= 0),
                code VARCHAR(30) UNIQUE,
                usable BOOLEAN DEFAULT TRUE,
                day DATE,
                timestamp TIMESTAMP WITH TIME ZONE DEFAULT now(),
                version INTEGER GENERATED BY DEFAULT AS IDENTITY
            ); -- end of schema
        """)
        self.assertEqual(tables, [{
            "name": "sales.Supply Order",
            "columns": [
                {"name": "order_id", "type": "integer", "sql_type": "BIGSERIAL", "required": True},
                {"name": "amount", "type": "number", "sql_type": "DECIMAL(12, 2)", "required": True},
                {"name": "code", "type": "string", "sql_type": "VARCHAR(30)", "required": False},
                {"name": "usable", "type": "boolean", "sql_type": "BOOLEAN", "required": False},
                {"name": "day", "type": "date", "sql_type": "DATE", "required": False},
                {"name": "timestamp", "type": "datetime", "sql_type": "TIMESTAMPTZ", "required": False},
                {"name": "version", "type": "integer", "sql_type": "INT", "required": True},
            ],
            "primary_key": ["order_id"],
            "foreign_keys": [],
            "unique_keys": [["code"]],
        }])

    def test_preserves_ordered_composite_keys_and_inline_references(self):
        tables = parse_ddl("""
            CREATE TABLE "Inventory".SUPPLIER (
                region TEXT, "CompanyID" UUID,
                CONSTRAINT supplier_pk PRIMARY KEY (region, "CompanyID"),
                CONSTRAINT supplier_unique UNIQUE ("CompanyID", region)
            );
            CREATE TABLE inventory.order_item (
                supplier_region TEXT, supplier_id UUID,
                order_id BIGINT REFERENCES orders ON DELETE CASCADE,
                product_id BIGINT REFERENCES catalog.product(id),
                CONSTRAINT supplier_fk FOREIGN KEY (supplier_region, supplier_id)
                    REFERENCES "Inventory".SUPPLIER(region, "CompanyID")
            );
        """)
        supplier, item = tables
        self.assertEqual(supplier["primary_key"], ["region", "CompanyID"])
        self.assertTrue(all(column["required"] for column in supplier["columns"]))
        self.assertEqual(supplier["unique_keys"], [["CompanyID", "region"]])
        self.assertEqual(item["foreign_keys"], [
            {"columns": ["order_id"], "target_table": "orders", "target_columns": []},
            {"columns": ["product_id"], "target_table": "catalog.product", "target_columns": ["id"]},
            {
                "columns": ["supplier_region", "supplier_id"],
                "target_table": "Inventory.supplier",
                "target_columns": ["region", "CompanyID"],
            },
        ])

    def test_rejects_statements_outside_the_create_table_subset(self):
        examples = [
            "",
            "-- schema omitted",
            "SELECT 1",
            "CREATE TABLE x (id INT); DROP TABLE x",
            "CREATE TABLE x AS SELECT 1",
            "CREATE TABLE x (LIKE other INCLUDING ALL)",
            "CREATE TABLE x (id INT) INHERITS (other)",
            "CREATE TABLE x (id INT) PARTITION BY RANGE (id)",
            "CREATE TABLE x (id INT DEFAULT (SELECT 1))",
            "CREATE TEMP TABLE x (id INT)",
            "CREATE TABLE x (id INT AUTO_INCREMENT)",
            "CREATE TABLE x (id INT",
            "CREATE TABLE x (payload TEXT[])",
            'CREATE TABLE "schema.table" (id INT)',
            'CREATE TABLE x (id INT REFERENCES "schema.table"(id))',
            "CREATE TABLE db.schema.x (id INT)",
        ]
        for ddl in examples:
            with self.subTest(ddl=ddl), self.assertRaises(ValueError):
                parse_ddl(ddl)

    def test_rejects_ambiguous_or_invalid_key_declarations(self):
        examples = [
            "CREATE TABLE x (id INT, ID INT)",
            "CREATE TABLE x (id INT); CREATE TABLE X (a INT)",
            "CREATE TABLE x (id INT, PRIMARY KEY (missing))",
            "CREATE TABLE x (id INT, PRIMARY KEY (id, id))",
            "CREATE TABLE x (id INT PRIMARY KEY, a INT PRIMARY KEY)",
            "CREATE TABLE x (id INT, UNIQUE (missing))",
            "CREATE TABLE x (id INT, FOREIGN KEY (missing) REFERENCES y (id))",
            "CREATE TABLE x (id INT, a INT, FOREIGN KEY (id, a) REFERENCES y (id))",
            "CREATE TABLE x (id INT NOT NULL NULL)",
            "CREATE TABLE x (id INT REFERENCES y(id) NOT ENFORCED)",
            "CREATE TABLE x (id INT REFERENCES y(id) MATCH PARTIAL)",
        ]
        for ddl in examples:
            with self.subTest(ddl=ddl), self.assertRaises(ValueError):
                parse_ddl(ddl)

    def test_adds_keys_from_alter_table_to_declared_tables(self):
        supplier, item = parse_ddl("""
            CREATE TABLE public.supplier (id INT, code TEXT);
            CREATE TABLE public.item (id INT, supplier_id INT);
            ALTER TABLE ONLY public.supplier
                ADD CONSTRAINT supplier_pk PRIMARY KEY (id),
                ADD CONSTRAINT supplier_code UNIQUE (code);
            ALTER TABLE public.item ADD PRIMARY KEY (id, supplier_id);
            ALTER TABLE ONLY public.item ADD CONSTRAINT item_supplier_fk
                FOREIGN KEY (supplier_id) REFERENCES public.supplier (id);
        """)
        self.assertEqual(supplier["primary_key"], ["id"])
        self.assertTrue(supplier["columns"][0]["required"])
        self.assertEqual(supplier["unique_keys"], [["code"]])
        self.assertEqual(item["primary_key"], ["id", "supplier_id"])
        self.assertEqual(item["foreign_keys"], [{
            "columns": ["supplier_id"],
            "target_table": "public.supplier",
            "target_columns": ["id"],
        }])

    def test_captures_table_and_column_descriptions(self):
        table, = parse_ddl("""
            CREATE TABLE public."Supplier" ("ID" UUID PRIMARY KEY, name TEXT);
            COMMENT ON TABLE Public."Supplier" IS 'First comment';
            COMMENT ON TABLE public."Supplier" IS 'Supplier''s record';
            COMMENT ON COLUMN public."Supplier"."ID" IS $$Vendor identifier; supplied externally$$;
        """)
        self.assertEqual(table["comment"], "Supplier's record")
        self.assertEqual(table["columns"][0]["comment"], "Vendor identifier; supplied externally")
        self.assertNotIn("comment", table["columns"][1])

    def test_rejects_out_of_scope_alterations_and_comments(self):
        examples = [
            "ALTER TABLE x ADD PRIMARY KEY (id)",
            "ALTER TABLE y ADD PRIMARY KEY (id)",
            "ALTER TABLE x ADD COLUMN status TEXT",
            "ALTER TABLE x ADD CHECK (id > 0)",
            "ALTER TABLE x RENAME TO y",
            "ALTER TABLE x DROP COLUMN id",
            "ALTER TABLE IF EXISTS x ADD PRIMARY KEY (id)",
            "ALTER TABLE x ADD UNIQUE (id), ADD COLUMN status TEXT",
            "ALTER TABLE x ADD FOREIGN KEY (id) REFERENCES y(id) NOT VALID",
            "ALTER TABLE x ADD PRIMARY KEY (missing)",
            "COMMENT ON SCHEMA x IS 'schema'",
            "COMMENT ON TABLE y IS 'unavailable'",
            "COMMENT ON COLUMN x.unavailable IS 'missing'",
            "COMMENT ON TABLE x IS NULL",
        ]
        with self.assertRaises(ValueError):
            parse_ddl(examples[0])
        for ddl in examples[1:]:
            with self.subTest(ddl=ddl), self.assertRaises(ValueError):
                parse_ddl(f"CREATE TABLE x (id INT); {ddl}")
        with self.assertRaises(ValueError):
            parse_ddl("CREATE TABLE x (id INT PRIMARY KEY); ALTER TABLE x ADD PRIMARY KEY (id)")

    def test_invalid_sql_is_not_echoed_into_logs_or_errors(self):
        with self.assertNoLogs("sqlglot"), self.assertRaises(ValueError) as caught:
            parse_ddl("ALTER TABLE x ADD CONSTRAINT upload_marker UNIQUE USING INDEX y")
        self.assertNotIn("upload_marker", str(caught.exception))

    def test_enforces_input_table_and_column_limits(self):
        with self.assertRaisesRegex(ValueError, "size limit"):
            parse_ddl(" " * (256 * 1024 + 1))
        with self.assertRaisesRegex(ValueError, "table limit"):
            parse_ddl(";".join(f"CREATE TABLE table_{n} (id INT)" for n in range(33)))
        with self.assertRaisesRegex(ValueError, "column limit"):
            parse_ddl("CREATE TABLE x (" + ", ".join(f"column_{n} INT" for n in range(101)) + ")")

    def test_mysql_show_create_table_preserves_keys_comments_and_types(self):
        vendor, lot = parse_ddl("""
            CREATE TABLE `supply`.`vendor` (
                `VendorID` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT 'Supplier ID',
                `name` VARCHAR(200) NOT NULL COMMENT 'Supplier''s legal name',
                `code` VARCHAR(30) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci,
                `active` BOOLEAN DEFAULT TRUE,
                `priority` TINYINT(1),
                PRIMARY KEY (`vendorid`),
                UNIQUE KEY `vendor_code` (`code`)
            ) ENGINE=InnoDB AUTO_INCREMENT=201 DEFAULT CHARSET=utf8mb4
              COLLATE=utf8mb4_unicode_ci COMMENT='Vendors' ROW_FORMAT=DYNAMIC;
            CREATE TABLE `supply`.`lot` (
                `lot_no` VARCHAR(40) PRIMARY KEY,
                `VendorRef` BIGINT UNSIGNED,
                `received_at` DATETIME(6),
                KEY `idx_vendor` (`VendorRef`)
            ) ENGINE=InnoDB;
            ALTER TABLE `supply`.`lot` ADD CONSTRAINT `fk_vendor`
                FOREIGN KEY (`vendorref`) REFERENCES `vendor` (`VENDORID`)
                ON DELETE RESTRICT ON UPDATE CASCADE;
        """, dialect="mysql")
        self.assertEqual(vendor["name"], "supply.vendor")
        self.assertEqual(vendor["primary_key"], ["VendorID"])
        self.assertEqual(vendor["unique_keys"], [["code"]])
        self.assertEqual(vendor["comment"], "Vendors")
        fields = {column["name"]: column for column in vendor["columns"]}
        self.assertEqual(fields["VendorID"], {
            "name": "VendorID", "type": "integer", "sql_type": "BIGINT UNSIGNED",
            "required": True, "comment": "Supplier ID",
        })
        self.assertEqual(fields["name"]["comment"], "Supplier's legal name")
        self.assertEqual(fields["active"]["type"], "boolean")
        self.assertEqual(fields["priority"]["type"], "integer")
        self.assertEqual(lot["columns"][-1]["type"], "datetime")
        self.assertEqual(lot["columns"][-1]["sql_type"], "DATETIME(6)")
        self.assertEqual(lot["foreign_keys"], [{
            "columns": ["VendorRef"], "target_table": "vendor", "target_columns": ["VendorID"],
        }])

    def test_mysql_rejects_unreliable_or_unsupported_schema_statements(self):
        for ddl in (
            "CREATE TABLE x (id INT, ID INT)",
            "CREATE TABLE x (id INT PRIMARY KEY, vendor_id INT REFERENCES y(id));",
            "CREATE TABLE x (id INT PRIMARY KEY, vendor_id INT, FOREIGN KEY (vendor_id) REFERENCES y(id)) ENGINE=MyISAM;",
            "CREATE TABLE y (id INT PRIMARY KEY) ENGINE=MyISAM; CREATE TABLE x (id INT, FOREIGN KEY (id) REFERENCES y(id)) ENGINE=InnoDB;",
            "CREATE TABLE y (id INT PRIMARY KEY) ENGINE=NDB; CREATE TABLE x (id INT, FOREIGN KEY (id) REFERENCES y(id)) ENGINE=InnoDB;",
            "CREATE TABLE x (id INT, FOREIGN KEY (id) REFERENCES y(id) DEFERRABLE INITIALLY DEFERRED);",
            "CREATE TABLE x (id INT, FOREIGN KEY (id) REFERENCES y(id) ON DELETE SET DEFAULT);",
            "CREATE TABLE x (id INT); ALTER TABLE ONLY x ADD PRIMARY KEY (id);",
            "CREATE TABLE x (id INT PRIMARY KEY, code TEXT, UNIQUE KEY ux (code(10)));",
            "CREATE TABLE x (id INT) /*!50100 ENGINE=MyISAM */;",
            "CREATE TABLE x (id INT); /*!40101 SET names utf8mb4 */;",
            "CREATE TABLE x (id INT); /*!40101 SET names utf8mb4 */",
            "CREATE TABLE x AS SELECT 1;",
            "CREATE TABLE x (id INT); INSERT INTO x VALUES (1);",
        ):
            with self.subTest(ddl=ddl), self.assertRaises(ValueError):
                parse_ddl(ddl, dialect="mysql")

    def test_mysql_executable_comment_markers_in_literals_are_text(self):
        table, = parse_ddl(
            "CREATE TABLE x (id INT COMMENT 'Text containing /*!') COMMENT='Example';",
            dialect="mysql",
        )
        self.assertEqual(table["columns"][0]["comment"], "Text containing /*!")

    def test_mysql_recognizes_ndb_storage_engine_aliases(self):
        vendor, lot = parse_ddl("""
            CREATE TABLE vendor (id INT PRIMARY KEY) ENGINE=NDB;
            CREATE TABLE lot (id INT PRIMARY KEY, vendor_id INT,
                FOREIGN KEY (vendor_id) REFERENCES vendor(id)) ENGINE=NDBCLUSTER;
        """, dialect="mysql")
        self.assertEqual(lot["foreign_keys"][0]["target_table"], vendor["name"])
